const formatMessage = (template: string, params?: Record<string, string | number>): string => {
  if (!params) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, token) => {
    const value = params[token];
    return value === undefined ? match : String(value);
  });
};

export const resolveOfficeLocale = (value: string | null | undefined): OfficeLocale => {
  if (!value) {
    return DEFAULT_OFFICE_LOCALE;
  }
  return supportedLocales.has(value as OfficeLocale) ? (value as OfficeLocale) : DEFAULT_OFFICE_LOCALE;
};

export const createOfficeTranslator = (locale: OfficeLocale): OfficeTranslator => {
  const localeDictionary = {
    ...englishDictionary,
    ...(dictionaries[locale] ?? {})
  };
  return (key, params) => {
    const template = localeDictionary[key] ?? key;
    return formatMessage(template, params);
  };
};

export const loadOfficeLocale = (storage?: Pick<Storage, "getItem">): OfficeLocale => {
  if (!storage) {
    return DEFAULT_OFFICE_LOCALE;
  }
  return resolveOfficeLocale(storage.getItem(OFFICE_LOCALE_STORAGE_KEY));
};

export const saveOfficeLocale = (locale: OfficeLocale, storage?: Pick<Storage, "setItem">): void => {
  if (!storage) {
    return;
  }
  storage.setItem(OFFICE_LOCALE_STORAGE_KEY, locale);
};
